#!/usr/bin/env node
/**
 * Regenerates the list of emoji that Google publishes an animated version of.
 *
 * Google hosts ~880 animated emoji (Lottie + WebP) on the same CDN as their
 * fonts, and publishes an index of which ones exist. We snapshot that index
 * into the repo so neither the editor nor the renderer has to call out to
 * Google just to know what's available -- they only fetch the actual artwork.
 *
 * Run by hand when Google adds new animated emoji:  node scripts/fetch-animated-emoji.mjs
 *
 * Artwork is CC BY 4.0 (Google Noto Emoji) -- see the credit in the caption panel.
 */
import { writeFileSync } from "node:fs";

const INDEX_URL = "https://googlefonts.github.io/noto-emoji-animation/data/api.json";
const OUT = new URL("../remotion/src/lib/animatedEmojiData.ts", import.meta.url);

const res = await fetch(INDEX_URL);
if (!res.ok) throw new Error(`${INDEX_URL} -> HTTP ${res.status}`);
const { icons } = await res.json();

// Each entry is [slug, character, searchText]. Array-of-arrays rather than
// objects purely to keep the shipped file small.
const rows = icons.map((icon) => {
  const slug = icon.codepoint;
  const char = String.fromCodePoint(...slug.split("_").map((h) => parseInt(h, 16)));
  const words = [
    ...(icon.tags ?? []).map((t) => t.replace(/:/g, "").replace(/-/g, " ")),
    ...(icon.categories ?? []),
  ];
  return [slug, char, [...new Set(words.join(" ").toLowerCase().split(/\s+/))].join(" ")];
});

// Emitted as TypeScript rather than JSON so plain `node` can run the module
// (and its self-check) without JSON import attributes.
writeFileSync(
  OUT,
  `// GENERATED by scripts/fetch-animated-emoji.mjs -- do not edit by hand.\n` +
    `// [codepoint slug, character, search words]. Artwork: Google Noto Emoji, CC BY 4.0.\n` +
    `const rows: [string, string, string][] = ${JSON.stringify(rows)};\nexport default rows;\n`
);
console.log(`wrote ${rows.length} animated emoji -> ${OUT.pathname}`);
