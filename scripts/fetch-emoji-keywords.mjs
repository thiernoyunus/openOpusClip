#!/usr/bin/env node
/**
 * Regenerates the emoji catalog the transcript emoji picker searches and
 * browses: every emoji, its name, the words people search it by, and the
 * category it sits in.
 *
 * Words come from three open lists, merged per emoji:
 *   - Unicode CLDR names + keywords (via emojibase-data, MIT) -- the same
 *     source phone keyboards build their emoji search on.
 *   - emojilib (MIT) -- everyday words CLDR leaves out ("lit", "meow").
 *   - Google's own tags for the emoji it animates.
 *
 * Run by hand when a new emoji version lands:  node scripts/fetch-emoji-keywords.mjs
 */
import { writeFileSync } from "node:fs";

const EMOJIBASE = "https://cdn.jsdelivr.net/npm/emojibase-data@17.0.0/en/data.json";
const EMOJILIB = "https://cdn.jsdelivr.net/npm/emojilib@4.0.3/dist/emoji-en-US.json";
const GOOGLE = "https://googlefonts.github.io/noto-emoji-animation/data/api.json";
const OUT = new URL("../dashboard/src/components/editor/emojiCatalogData.js", import.meta.url);

// Newest emoji version every supported Mac/Windows can draw as a plain
// character. Anything newer shows up as an empty box, so it's only offered
// when Google has animated artwork for it.
const PLAIN_MAX_VERSION = 15.0;

// Unicode group index -> picker tab, in the order the iPhone keyboard uses.
// Smileys and People share a tab there too.
const TAB_BY_GROUP = { 0: 0, 1: 0, 3: 1, 4: 2, 6: 3, 5: 4, 7: 5, 8: 6, 9: 7 };

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
}

const [base, lib, google] = await Promise.all([getJson(EMOJIBASE), getJson(EMOJILIB), getJson(GOOGLE)]);

// Glue words that leak in from multi-word tags ("private eye or ...") and
// would otherwise make "or" find a detective.
const FILLER = new Set(["a", "an", "and", "or", "of", "the", "for", "with", "in", "on", "to", "at", "by", "is"]);

const bare = (s) => s.replace(/\uFE0F/g, "");
const toneless = (s) => s.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, "");
const words = (s) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean);

// Extra words keyed by the bare character (no variation selector), since the
// three lists don't agree on when to write U+FE0F.
const extra = new Map();
const addExtra = (char, list) => {
  const key = bare(char);
  if (!extra.has(key)) extra.set(key, new Set());
  for (const w of list) extra.get(key).add(w);
};
for (const [char, keys] of Object.entries(lib)) addExtra(char, keys.flatMap(words));

// The three lists disagree on U+FE0F: emojibase writes "👍\uFE0F", which is legal
// but not how keyboards type it. Prefer the spelling Google or emojilib uses.
const spelled = new Map(Object.keys(lib).map((c) => [bare(c), c]));

// Google lists its animated emoji most-used first; that order doubles as a
// popularity rank so "heart" leads with ❤\uFE0F rather than 💟.
const popularity = new Map();
const animated = new Set();
for (const icon of google.icons) {
  const char = String.fromCodePoint(...icon.codepoint.split("_").map((h) => parseInt(h, 16)));
  animated.add(bare(char));
  if (!popularity.has(toneless(bare(char)))) popularity.set(toneless(bare(char)), popularity.size);
  spelled.set(bare(char), char);
  addExtra(char, (icon.tags ?? []).flatMap(words));
}
// Google also tags each skin-tone copy; fold those words into the base emoji.
for (const key of [...extra.keys()]) {
  const t = toneless(key);
  if (t !== key) addExtra(t, extra.get(key));
}

const rows = [];
for (const e of [...base].sort((a, b) => (a.order ?? 1e9) - (b.order ?? 1e9))) {
  const tab = TAB_BY_GROUP[e.group];
  if (tab === undefined || e.label.startsWith("regional indicator")) continue;
  const plain = e.version <= PLAIN_MAX_VERSION;
  const isAnimated = animated.has(bare(e.emoji));
  if (!plain && !isAnimated) continue;

  const nameWords = new Set(words(e.label));
  const kw = new Set();
  for (const w of [...(e.tags ?? []).flatMap(words), ...(extra.get(bare(e.emoji)) ?? [])]) {
    if (!nameWords.has(w) && !FILLER.has(w)) kw.add(w);
  }
  // Five single-tone copies, lightest to darkest, when the emoji has them.
  const tones = (e.skins ?? []).filter((s) => typeof s.tone === "number").sort((a, b) => a.tone - b.tone);
  const skins = tones.length === 5 ? tones.map((s) => spelled.get(bare(s.emoji)) ?? s.emoji) : undefined;

  const rank = popularity.get(bare(e.emoji)) ?? -1;
  const row = [spelled.get(bare(e.emoji)) ?? e.emoji, e.label, [...kw].join(" "), tab, plain ? 1 : 0, rank];
  if (skins) row.push(skins);
  rows.push(row);
}

writeFileSync(
  OUT,
  `// GENERATED by scripts/fetch-emoji-keywords.mjs -- do not edit by hand.\n` +
    `// [character, name, search words, tab, shows as a plain character (1/0), popularity rank (-1 = unranked), skin tones?]\n` +
    `// Words: Unicode CLDR via emojibase-data (MIT), emojilib (MIT), Google Noto Emoji tags.\n` +
    `const rows = ${JSON.stringify(rows)};\nexport default rows;\n`
);
console.log(`wrote ${rows.length} emoji -> ${OUT.pathname}`);
